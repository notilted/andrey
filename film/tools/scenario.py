"""Полный сценарий с таймкодами из таймлайна: python3 tools/scenario.py -> ../script/сценарий.md"""
import json, os

ROOT = os.path.join(os.path.dirname(__file__), "..")
tl = json.load(open(os.path.join(ROOT, "src", "data", "film.json")))
lines = {l["id"]: l for l in json.load(open(os.path.join(ROOT, "..", "script", "lines.json")))}
m = tl["marks"]
tc = lambda t: f"{int(t // 60):02}:{t % 60:05.2f}"

SCENES = [
    ("s1", "СЦЕНА 1. «ОПОВЕЩЕНИЕ»", "Москва, 23:41. Камера плывёт между многоэтажками: в окнах мужчина у телевизора, женщина с чайником, Марк и Алиса за столом. Наезд в окно — квартира в разрезе. Алиса рисует. Сигнал оповещения, красное уведомление «РАКЕТНАЯ УГРОЗА», отсчёт 17:00. Марк смотрит в окно, с улицы — громкоговоритель и сирены. Повторная вибрация: сообщение с собственного номера «МАРК. НЕ СПУСКАЙСЯ В МЕТРО». Крупный план лица Марка. Резкая склейка."),
    ("s2", "СЦЕНА 2. «ЛЕСТНИЦА»", "Подъезд в разрезе: жильцы на всех этажах выходят из квартир и спускаются. Марк ведёт Алису по маршам. Сверху догоняет Галина с клеткой попугая. Короткая комическая сцена; Алиса улыбается. Свет мигает — улыбка исчезает."),
    ("s3", "СЦЕНА 3. «ШАХМАТИСТ»", "Убежище № 17 в подвале. Аварийные лампы, люди с телефонами. В углу Лев переставляет шахматного коня. Марк замечает телефон Льва: у Льва 12:00, у Марка 08:59. Таймеры идут с разной скоростью."),
    ("s4", "СЦЕНА 4. «ЛОЖНАЯ ТРЕВОГА»", "Динамик: «Угроза отменена». Люди радуются и идут к выходу. Лев замечает, что сирены всё ещё воют. Марк встаёт у двери и не выпускает людей. Мощный удар снаружи, лампы гаснут — полная темнота, только дыхание и звон в ушах."),
    ("s5", "СЦЕНА 5. «ГОЛОС»", "Красное аварийное освещение. Алиса держит папу за руку. Сообщение: «АЛИСА ДОЛЖНА ОСТАТЬСЯ ВНУТРИ». Три медленных удара в гермодверь. «Спасатели». Галина идёт к двери — Марк останавливает её. Голос за дверью — голосом Марка: «Алиса, открой. Это папа»."),
    ("s6", "СЦЕНА 6. «ДВОЙНИК»", "Включается монитор видеонаблюдения. На экране коридор за дверью: там стоит человек, неотличимый от Марка, и смотрит прямо в камеру."),
    ("s7", "СЦЕНА 7. «ЭТАП ПЕРВЫЙ»", "Отсчёт достигает нуля. Все телефоны загораются: «ЭТАП 1 ЗАВЕРШЁН. ОБНАРУЖЕНО 2 847 193 КОПИИ». Алиса поворачивается к Марку. Темнота. Три тихих удара в дверь. Титр «17 МИНУТ — конец первой части»."),
]
order = [s[0] for s in SCENES] + ["end"]
out = ["# «17 МИНУТ» — полный сценарий", "",
       f"Анимационный апокалиптический триллер · {tc(tl['duration'])} · 1080×1920 · 30 fps", "",
       "**Персонажи:** Марк (38, инженер) · Алиса (9, его дочь) · Галина Петровна (67, соседка с попугаем) · Лев (31, шахматист)", ""]
for i, (key, title, action) in enumerate(SCENES):
    a, b = m[key], m[order[i + 1]] if order[i + 1] in m else tl["duration"]
    out += [f"## {title}", f"`{tc(a)} – {tc(b)}`", "", action, ""]
    for d in tl["dialogue"]:
        if a <= d["start"] < b:
            l = lines[d["id"]]
            note = f" *({l['note']})*" if l.get("note") else ""
            out.append(f"- `{tc(d['start'])}` **{d['name']}**{note}: {l['text'].replace('...', '…')}")
    out.append("")
open(os.path.join(ROOT, "..", "script", "сценарий.md"), "w", encoding="utf-8").write("\n".join(out))
print("ok")
